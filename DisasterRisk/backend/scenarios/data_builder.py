def _make_irregular_polygon(
    lon: float, lat: float, rx: float, ry: float, seed_idx: int, points: int = 12
) -> list[list[float]]:
    coords: list[list[float]] = []
    for i in range(points):
        angle = (2.0 * math.pi * i) / points
        jitter = 0.82 + 0.28 * math.sin(angle * 3.0 + seed_idx * 1.7) + 0.1 * math.cos(angle * 5.0 - seed_idx)
        px = round(lon + rx * jitter * math.cos(angle), 5)
        py = round(lat + ry * jitter * math.sin(angle), 5)
        coords.append([px, py])
    coords.append(coords[0])
    return coords


